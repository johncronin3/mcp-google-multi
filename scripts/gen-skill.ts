import fs from 'node:fs';
import path from 'node:path';

// Generates skills/google-workspace/reference/<service>.md from the real tool
// registry, so the agent skill's argument tables can never drift from the
// code. Modeled on scripts/gen-coverage.ts: build the registry with every
// curated service, every generated service, and no account restrictions, so
// the tables are the full ceiling rather than one deployment's view.

process.env.GOOGLE_ACCOUNTS ??= 'example:user@example.com';
process.env.GOOGLE_CLIENT_ID ??= 'skillgen';
process.env.GOOGLE_CLIENT_SECRET ??= 'skillgen';

const { z } = await import('zod');
const { ToolRegistry } = await import('../src/registry.js');
const { SERVICES } = await import('../src/services.js');
const { GENERATED_SERVICES } = await import('../src/tools/generated/index.js');
const { registerDiscoverTools } = await import('../src/discover.js');
const { registerEscapeTools } = await import('../src/tools/google-api.js');
const { registerAccountTools } = await import('../src/tools/accounts-tool.js');
type Registry = InstanceType<typeof ToolRegistry>;
type ToolEntry = Registry['tools'][number];

const FULL_POLICY = { profile: 'full-writes' as const, readOnly: false, allow: [], deny: [] };

function makeRegistry(): Registry {
  const server = {
    registerTool: () => 'ok',
    sendToolListChanged: () => {},
    server: { setRequestHandler: () => {} },
  };
  return new ToolRegistry(server as never, FULL_POLICY);
}

const curatedOnly = makeRegistry();
for (const svc of SERVICES) svc.register(curatedOnly);
const curatedNames = new Set(curatedOnly.tools.filter((t) => !t.meta).map((t) => t.name));

const full = makeRegistry();
for (const svc of SERVICES) svc.register(full);
for (const gen of GENERATED_SERVICES) gen.register(full);

const services = [...new Set(full.tools.filter((t) => !t.meta).map((t) => t.service))].sort();

// A second registry covering the SKILL.md-referenced meta tools too
// (account_list, discover_all/_reset, {service}_discover, the escape hatch):
// SKILL.md's drift test validates tool/argument names against this one, kept
// separate from `full` so the per-service reference tables above never pick
// up a meta tool by accident.
const withMeta = makeRegistry();
for (const svc of SERVICES) svc.register(withMeta);
for (const gen of GENERATED_SERVICES) gen.register(withMeta);
registerDiscoverTools(withMeta, FULL_POLICY);
registerEscapeTools(withMeta, FULL_POLICY);
registerAccountTools(withMeta);

export function allToolNames(): string[] {
  return withMeta.tools.map((t) => t.name);
}

export function argNamesFor(toolName: string): string[] | undefined {
  const tool = withMeta.tools.find((t) => t.name === toolName);
  return tool ? Object.keys(tool.inputShape) : undefined;
}

function jsonTypeOf(prop: Record<string, unknown> | undefined): string {
  if (!prop) return 'string';
  if (prop.enum) return 'enum';
  if (typeof prop.type === 'string') return prop.type;
  if (Array.isArray(prop.type)) return prop.type.join(' | ');
  if (Array.isArray(prop.anyOf)) {
    const parts = (prop.anyOf as Record<string, unknown>[]).map(jsonTypeOf).filter(Boolean);
    return [...new Set(parts)].join(' | ') || 'string';
  }
  return 'string';
}

function argTable(tool: ToolEntry): string[] {
  const argNames = Object.keys(tool.inputShape);
  if (argNames.length === 0) return ['No arguments.', ''];
  const schema = z.toJSONSchema(z.object(tool.inputShape), { target: 'draft-7', io: 'input' }) as {
    properties?: Record<string, Record<string, unknown>>;
    required?: string[];
  };
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines = ['| Argument | Type | Required | Description |', '|---|---|---|---|'];
  for (const name of argNames) {
    const prop = props[name];
    const type = jsonTypeOf(prop);
    const req = required.has(name) ? 'required' : 'optional';
    const desc = String(prop?.description ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');
    lines.push(`| \`${name}\` | ${type} | ${req} | ${desc} |`);
  }
  lines.push('');
  return lines;
}

function renderService(service: string): string {
  const all = full.tools.filter((t) => !t.meta && t.service === service);
  const curated = all.filter((t) => curatedNames.has(t.name)).sort((a, b) => a.name.localeCompare(b.name));
  const generatedCount = all.length - curated.length;

  const lines: string[] = [
    `# ${service}`,
    '',
    '<!-- GENERATED by scripts/gen-skill.ts, do not edit by hand. Regenerate: npm run gen:skill -->',
    '',
  ];

  if (curated.length === 0) {
    lines.push(
      `This service has no curated tools. All ${generatedCount} \`${service}\` tools are generated from Google's API ` +
        `Discovery document: they take Google's own Discovery parameter names (not a hand-written schema), and ` +
        `\`${service}_discover\` lists each one with its arguments.`,
      '',
    );
    return lines.join('\n');
  }

  lines.push(
    `${curated.length} curated tool${curated.length === 1 ? '' : 's'}` +
      (generatedCount > 0
        ? `, plus ${generatedCount} generated tool${generatedCount === 1 ? '' : 's'} (Google Discovery parameter names; see \`${service}_discover\`).`
        : '.'),
    '',
  );

  for (const tool of curated) {
    lines.push(`## \`${tool.name}\``, '', `Class: ${tool.cud}`, '', tool.description.split('\n')[0], '', ...argTable(tool));
  }

  return lines.join('\n');
}

export function generateReferenceFiles(): Record<string, string> {
  const files: Record<string, string> = {};
  for (const service of services) files[`${service}.md`] = renderService(service);
  return files;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const outDir = path.join(process.cwd(), 'skills/google-workspace/reference');
  fs.mkdirSync(outDir, { recursive: true });
  const files = generateReferenceFiles();
  for (const [name, content] of Object.entries(files)) {
    fs.writeFileSync(path.join(outDir, name), content);
  }
  console.log(`skills/google-workspace/reference: ${Object.keys(files).length} files for ${services.length} services.`);
}
